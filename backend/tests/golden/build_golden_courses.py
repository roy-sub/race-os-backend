NODE_SPACING_M = 100.0  # SOLVER_MODEL.md B.1: "Elevation series: 100 m node spacing"


def leg_series(segments, start_h=0.0):
    """Node series (s, h) at 100 m spacing reproducing each segment's net
    gradient exactly, per SOLVER_MODEL.md B.1."""
    s = 0.0
    h = start_h
    nodes = [(0.0, h)]
    for seg in segments:
        length = seg["km"] * 1000.0
        steps = max(1, int(round(length / NODE_SPACING_M)))
        step = length / steps
        for _ in range(steps):
            h += seg["net_gradient"] * step
            s += step
            nodes.append((round(s, 3), round(h, 4)))
    return nodes


def shift_to_mean(nodes, target_mean):
    """Offset the whole series so its distance-weighted mean matches B.1."""
    total = nodes[-1][0]
    if total <= 0:
        return nodes
    weighted = sum(
        (nodes[i][1] + nodes[i + 1][1]) / 2.0 * (nodes[i + 1][0] - nodes[i][0])
        for i in range(len(nodes) - 1)
    )
    delta = target_mean - weighted / total
    return [(s, round(h + delta, 4)) for s, h in nodes]


def gain(nodes):
    return round(sum(max(0.0, nodes[i + 1][1] - nodes[i][1]) for i in range(len(nodes) - 1)), 1)


def lap_segments(lap_km, gradients, laps, name):
    """Equal-quarter lap pattern, repeated. B.1's run construction."""
    out = []
    quarter = lap_km / len(gradients)
    for lap in range(1, laps + 1):
        for i, g in enumerate(gradients, start=1):
            out.append({"name": f"{name} lap {lap} q{i}", "km": quarter, "net_gradient": g})
    return out


def scaled_lap_segments(total_km, laps, quarters, target_gain_m, name):
    """A symmetric lap profile scaled so total ascent is exactly `target_gain_m`.

    Used where B.1 states a run leg's aggregate gain but not its segments; this
    reproduces the document's number rather than inventing a different one.
    """
    lap_km = total_km / laps
    quarter_km = lap_km / quarters
    # Half the quarters climb, half descend, symmetric so the lap closes.
    ups = quarters // 2
    per_lap_gain = target_gain_m / laps
    g_up = per_lap_gain / (ups * quarter_km * 1000.0)
    pattern = [g_up if i < ups else -g_up for i in range(quarters)]
    return lap_segments(lap_km, pattern, laps, name)


