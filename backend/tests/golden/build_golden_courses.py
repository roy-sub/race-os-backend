"""Build the solver's golden course fixtures from SOLVER_MODEL.md §B.1.

These are SYNTHETIC and MUST STAY SO. They are the frozen inputs of the solver's
golden-file regression suite (`RaceOS_Build_Spec.md` Part 19.2), and they are
deliberately unrelated to the nine seeded bundles that
`pipelines/course-ingest` produces -- even though `C-TRAM` shares a name and
coordinates with Tramuntana Full.

The reason is a hard one. If a golden case read a pipeline-generated bundle,
regenerating a course would silently change the golden expectations, and the
solver's determinism guarantee would become a property of the routing engine
rather than of the solver. So: static files, checked in, generated by this
script and nothing else.

    python backend/tests/golden/build_golden_courses.py

This script imports nothing from `course_ingest`. That is deliberate and is
asserted by `pipelines/course-ingest/tests/test_golden_isolation.py`.
"""
